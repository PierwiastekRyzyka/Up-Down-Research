"""Two-sided maker bids: buy both Up and Down at b (e.g. 0.49) before the window starts.

If both legs fill, the pair pays 1 - 2b with no directional risk. If only one leg fills,
the position is a directional bet bought at b. Fills are inferred from trades:
a resting bid on Up at b is hit by a taker selling Up at <= b or buying Down at >= 1 - b,
so it fills when the Up-equivalent trade price reaches b.

touch:   fill when the Up-equivalent price trades at or through b (optimistic, front of queue)
through: fill only when it trades strictly through b (conservative, back of queue)

Unfilled legs are cancelled at `cancel` seconds into the window. Makers pay no fee; the
rebate during the sample was 20% of the taker fee generated by the fill, 0.2 * 0.07 * p(1-p).
"""
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from pm5m.config import RAW, TAKER_FEE
from pm5m.plotting import DARK, INK, LIGHT, MID, save
from pm5m.results import write
from pm5m.sample import Btc, load_markets
from pm5m.stats import tstat

REBATE = 0.2 * TAKER_FEE
LEVELS = (0.45, 0.46, 0.47, 0.48, 0.49)
CANCELS = (0, 30, 60, 120, 240, 300)
PLACE = -300                                   # orders resting from 5 minutes before the start

m = load_markets()
btc = Btc.load()
t = pd.read_parquet(RAW / "trades.parquet", columns=["start_ts", "ts", "outcome_index", "price"])
t = t[t.start_ts.isin(m.index)]
t = t.assign(rel=t.ts - t.start_ts, up_px=np.where(t.outcome_index == 0, t.price, 1 - t.price))
t = t[(t.rel >= PLACE) & (t.rel < 300)].sort_values(["start_ts", "ts"])
by_market = {k: (g.rel.to_numpy(), g.up_px.to_numpy()) for k, g in t.groupby("start_ts")}
up = m.up.reindex(list(by_market)).to_numpy()
sigma = m.sigma.reindex(list(by_market)).to_numpy()


def first_fill(rel, px, hit, cancel):
    idx = np.flatnonzero(hit & (rel < cancel))
    return rel[idx[0]] if len(idx) else None


def simulate(b, cancel, mode):
    rows = []
    for (start, (rel, px)), won_up, sg in zip(by_market.items(), up, sigma):
        hit_up = px < b if mode == "through" else px <= b
        hit_dn = px > 1 - b if mode == "through" else px >= 1 - b
        fu, fd = first_fill(rel, px, hit_up, cancel), first_fill(rel, px, hit_dn, cancel)
        rebate = REBATE * b * (1 - b)
        if fu is not None and fd is not None:
            rows.append(("both", 1 - 2 * b + 2 * rebate, np.nan, np.nan, start))
        elif fu is not None or fd is not None:
            leg_up = fu is not None
            when = fu if leg_up else fd
            won = won_up if leg_up else not won_up
            fair = np.nan
            if when >= 1:
                p = float(btc.fair_up(np.array([start]), np.array([int(when)]), np.array([sg]))[0])
                fair = p if leg_up else 1 - p
            rows.append(("one", float(won) - b + rebate, float(won), fair, start))
        else:
            rows.append(("none", 0.0, np.nan, np.nan, start))
    return pd.DataFrame(rows, columns=["state", "pnl", "won", "fair_at_fill", "start_ts"])


def summary(d, b):
    n = len(d)
    one = d[d.state == "one"]
    pnl_c = 100 * d.pnl
    return {"markets": n, "both_pct": 100 * (d.state == "both").mean(), "one_pct": 100 * (d.state == "one").mean(),
            "none_pct": 100 * (d.state == "none").mean(),
            "single_leg_win_rate": float(one.won.mean()) if len(one) else None,
            "single_leg_model_value_at_fill": float(one.fair_at_fill.mean()) if one.fair_at_fill.notna().any() else None,
            "single_leg_pnl_c": float(100 * one.pnl.mean()) if len(one) else None,
            "pair_pnl_c": 100 * (1 - 2 * b + 2 * REBATE * b * (1 - b)),
            "pnl_c_per_market": float(pnl_c.mean()), "t": tstat(pnl_c),
            "pnl_c_per_market_H1": float(pnl_c[d.start_ts.isin(m.index[m.half == "H1"])].mean()),
            "pnl_c_per_market_H2": float(pnl_c[d.start_ts.isin(m.index[m.half == "H2"])].mean())}


def hedge_on_fill(b, mode, delay=1, window=5):
    """When one leg fills, cancel the other and buy the opposite token as a taker
    at the median trade price over [fill + delay, fill + delay + window)."""
    out = []
    for (start, (rel, px)), won_up in zip(by_market.items(), up):
        hit_up = px < b if mode == "through" else px <= b
        hit_dn = px > 1 - b if mode == "through" else px >= 1 - b
        iu, idn = np.flatnonzero(hit_up), np.flatnonzero(hit_dn)
        if not len(iu) and not len(idn):
            continue
        leg_up = len(iu) and (not len(idn) or rel[iu[0]] <= rel[idn[0]])
        when = rel[iu[0]] if leg_up else rel[idn[0]]
        later = (rel >= when + delay) & (rel < when + delay + window)
        if not later.any():
            continue
        up_now = float(np.median(px[later]))
        other = 1 - up_now if leg_up else up_now           # price of the opposite token
        fee = TAKER_FEE * other * (1 - other)
        pnl = 1 - b - other - fee + REBATE * b * (1 - b)
        out.append(pnl)
    pnl_c = 100 * np.array(out)
    return {"markets": len(out), "pnl_c": float(pnl_c.mean()), "t": tstat(pnl_c),
            "share_profitable_pct": float(100 * (pnl_c > 0).mean())}


res = {"placement_s": PLACE, "rebate_rate": REBATE, "grid": {}}
for mode in ("touch", "through"):
    for b in LEVELS:
        for c in CANCELS:
            res["grid"][f"{mode}|b={b:.2f}|cancel={c}s"] = summary(simulate(b, c, mode), b)
res["hedge_on_fill"] = {f"{mode}|b={b:.2f}": hedge_on_fill(b, mode) for mode in ("touch", "through") for b in LEVELS}
pre = t[t.rel < 0]
res["pre_start"] = {"share_of_trades_pct": 100 * len(pre) / len(t),
                    "median_up_price": float(pre.up_px.median()),
                    "markets_with_pre_start_trade_pct": 100 * pre.start_ts.nunique() / len(by_market)}
write("08_two_sided_bids", res)

# figure: outcome mix when held to the end, and expected PnL by bid level
fig, axs = plt.subplots(1, 2, figsize=(9.6, 3.5))
x = np.arange(len(LEVELS))
g = res["grid"]
for j, (mode, c, color, style) in enumerate((("touch", 60, INK, "o-"), ("through", 60, DARK, "s--"),
                                              ("touch", 300, MID, "^-"), ("through", 300, LIGHT, "v--"))):
    axs[1].plot(LEVELS, [g[f"{mode}|b={b:.2f}|cancel={c}s"]["pnl_c_per_market"] for b in LEVELS], style, color=color,
                label=f"{'dotknięcie' if mode == 'touch' else 'przejście'}, " + ("do końca okna" if c == 300 else f"anulowanie po {c} s"))
axs[1].axhline(0, color="#333333", lw=.8)
axs[1].set_xticks(LEVELS, [f"{b:.2f}".replace(".", ",") for b in LEVELS])
axs[1].set(xlabel="cena zleceń kupna b [USD]", ylabel="średni PnL na rynek [¢ na akcję]", title="Wynik strategii na rynek")
axs[1].legend(fontsize=7, loc="lower left")
key = lambda b: g[f"touch|b={b:.2f}|cancel=300s"]
both = [key(b)["both_pct"] for b in LEVELS]
one = [key(b)["one_pct"] for b in LEVELS]
axs[0].bar(x, both, .6, color=INK, label="obie nogi")
axs[0].bar(x, one, .6, bottom=both, color=LIGHT, label="jedna noga")
axs[0].set_xticks(x, [f"{b:.2f}".replace(".", ",") for b in LEVELS])
axs[0].set(xlabel="cena zleceń kupna b [USD]", ylabel="% rynków", title="Wypełnienia (dotknięcie, do końca okna)")
axs[0].set_ylim(0, 118)
axs[0].legend(fontsize=7, ncol=2, loc="upper center")
save(fig, "fig10_two_sided_bids.png")
